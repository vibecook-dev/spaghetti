/** Session-list metadata projected from Claude Code transcript records. */

export interface ClaudeSessionMetadataProjection {
  humanPrompt?: string;
  aiTitle?: string;
  customTitle?: string;
}

const SYNTHETIC_USER_PREFIXES = [
  '<local-command-caveat>',
  '<local-command-stdout>',
  '<command-name>',
  '<command-message>',
  '<task-notification>',
  '<system-reminder>',
  '<ide_opened_file>',
  '<ide_selection>',
] as const;

function nonEmptyString(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined;
  const trimmed = value.trim();
  return trimmed ? trimmed : undefined;
}

function firstTextContent(record: Record<string, unknown>): string | undefined {
  const message = record.message as Record<string, unknown> | undefined;
  const content = message?.content;
  if (typeof content === 'string') return nonEmptyString(content);
  if (!Array.isArray(content)) return undefined;
  for (const candidate of content) {
    if (!candidate || typeof candidate !== 'object') continue;
    const block = candidate as Record<string, unknown>;
    if (block.type === 'text') {
      const text = nonEmptyString(block.text);
      if (text) return text;
    }
  }
  return undefined;
}

export function isClaudeSyntheticPromptText(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return true;
  const normalized = trimmed.toLowerCase();
  return SYNTHETIC_USER_PREFIXES.some((prefix) => normalized.startsWith(prefix));
}

/**
 * Session-index entries are unvalidated JSON: `firstPrompt` is typed `string`
 * but is routinely absent on disk, so anything non-string collapses to the
 * same placeholder the parser uses for an unreadable transcript.
 */
export function normalizeClaudeFirstPrompt(value: unknown): string {
  if (typeof value !== 'string') return 'No prompt';
  return isClaudeSyntheticPromptText(value) ? 'No prompt' : value;
}

export function extractClaudeHumanPrompt(raw: unknown): string | undefined {
  if (!raw || typeof raw !== 'object') return undefined;
  const record = raw as Record<string, unknown>;
  if (record.type !== 'user') return undefined;
  if (
    record.isMeta === true ||
    record.isSidechain === true ||
    record.isCompactSummary === true ||
    record.isVisibleInTranscriptOnly === true
  ) {
    return undefined;
  }

  const text = firstTextContent(record);
  if (!text) return undefined;
  if (isClaudeSyntheticPromptText(text)) return undefined;
  return text.slice(0, 200);
}

/** True for user-role rows generated by Claude rather than typed by a human. */
export function isClaudeSyntheticUserRecord(raw: unknown): boolean {
  if (!raw || typeof raw !== 'object') return false;
  const record = raw as Record<string, unknown>;
  if (record.type !== 'user' || record.isCompactSummary === true || record.isVisibleInTranscriptOnly === true) {
    return false;
  }
  if (record.isMeta === true) return true;
  const text = firstTextContent(record);
  if (!text) return false;
  return isClaudeSyntheticPromptText(text);
}

export function extractClaudeSessionMetadata(raw: unknown): ClaudeSessionMetadataProjection | undefined {
  if (!raw || typeof raw !== 'object') return undefined;
  const record = raw as Record<string, unknown>;
  if (record.type === 'ai-title') {
    const aiTitle = nonEmptyString(record.aiTitle);
    return aiTitle ? { aiTitle } : undefined;
  }
  if (record.type === 'custom-title') {
    const customTitle = nonEmptyString(record.customTitle);
    return customTitle ? { customTitle } : undefined;
  }
  const humanPrompt = extractClaudeHumanPrompt(record);
  return humanPrompt ? { humanPrompt } : undefined;
}
